/**
 * The statically-shaped parts of the page. Every element is looked up once at
 * startup so handlers can reference `ui.something` instead of re-querying the
 * DOM, and a missing id fails loudly at boot rather than on first interaction.
 */

const element = <T extends HTMLElement>(id: string): T => {
  const found = document.getElementById(id);
  if (found === null) throw new Error(`missing #${id}`);
  return found as T;
};

